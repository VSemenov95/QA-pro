import asyncio, os, json
from playwright.async_api import async_playwright
D=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(D)
html=open(os.path.join(ROOT,'tc-agent.html'),encoding='utf-8').read()
skel='<!doctype html><html><head><meta charset=utf8><meta name=viewport content="width=device-width,initial-scale=1"><style>[hidden]{display:none!important}body{margin:0}</style></head><body>'+html+'</body></html>'
standalone=open(os.path.join(ROOT,'qa-pro.html'),encoding='utf-8').read()
async def route(r):
    u=r.request.url
    if u.startswith('http://app.test/'): return await r.fulfill(body=skel, content_type='text/html; charset=utf-8')
    if u.startswith('http://local.test/'): return await r.fulfill(body=standalone, content_type='text/html; charset=utf-8')
    await r.abort()
async def answered(pg, n):
    await pg.wait_for_function(f"() => document.querySelectorAll('#help-list .hq-a:not(.st-pending)').length >= {n}", timeout=20000); await pg.wait_for_timeout(300)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); errs=[]
        ctx=await b.new_context(viewport={'width':1360,'height':950})
        await ctx.add_init_script(path=os.path.join(D,'mockgen.js')); await ctx.add_init_script(path=os.path.join(D,'mock.js'))
        await ctx.add_init_script(script='window.__QA_DEBUG = 1;')
        await ctx.route('**/*', route)
        pg=await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        pg.on('console', lambda m: errs.append('CONSOLE '+m.text) if m.type=='error' and 'net::' not in m.text else None)
        await pg.goto('http://app.test/'); await pg.wait_for_timeout(1500)
        await pg.click('#btn-run'); await pg.wait_for_timeout(400); await pg.wait_for_selector('#btn-run:not([hidden])', timeout=60000); await pg.wait_for_timeout(1000)
        await pg.click('[data-mode=help]'); await pg.wait_for_timeout(300)
        await pg.click('[data-act=help-view][data-v=qa]'); await pg.wait_for_timeout(200)
        vis = await pg.evaluate("""() => ({ tabs: !document.querySelector('#tabs').hidden, cfg: !document.querySelector('#rules-panel').hidden, run: !document.querySelector('.run-panel').hidden, docs: !document.querySelector('[aria-labelledby=h-docs]').hidden, provCards: document.querySelectorAll('#prov-list .prov').length, outs: !document.querySelector('#outs').closest('.field').hidden, newses: !document.querySelector('#btn-newses').hidden, steps: [...document.querySelectorAll('.rail .step-n')].filter(e => e.offsetParent).map(e => e.textContent).join(',') })""")
        print('H1 visibility:', vis)
        print('H1 head:', (await pg.inner_text('#help-head')).replace('\n',' | '))
        await pg.screenshot(path=os.path.join(D,'v13_help_empty.png'))
        await pg.evaluate('window.__prompts = []')
        await pg.click('[data-act=help-suggest] >> nth=1'); await answered(pg, 1)
        print('H2 answer:', (await pg.inner_text('#help-list .hq:last-child')).replace('\n',' | '))
        pr = await pg.evaluate("window.__prompts.find(p => p.includes('справочная служба'))")
        print('H2 prompt blocks:', [l for l in pr.split('\n') if l.startswith('[')][:8], '| len', len(pr))
        await pg.fill('#help-input', 'Какие ограничения и лимиты описаны?'); await pg.press('#help-input', 'Enter'); await answered(pg, 2)
        print('H3 repeat:', (await pg.inner_text('#help-list .hq:last-child .hq-foot')).replace('\n',' | '), '| model calls:', await pg.evaluate("window.__prompts.filter(p => p.includes('справочная служба')).length"))
        await pg.fill('#help-input', 'Как работает оплата картой?'); await pg.click('#help-send'); await answered(pg, 3)
        print('H4 not found:', (await pg.inner_text('#help-list .hq:last-child')).replace('\n',' | '))
        await pg.click('#help-list .hq:last-child [data-act=help-open-add]'); await pg.wait_for_timeout(800)
        print('H5 open block:', (await pg.inner_text('#help-open')).replace('\n',' | '))
        await pg.click('[data-act=help-ans-open] >> nth=-1'); await pg.wait_for_timeout(200)
        await pg.fill('[data-help-ans]', 'Оплата картой в этом релизе не поддерживается'); await pg.press('[data-help-ans]', 'Enter'); await pg.wait_for_timeout(800)
        print('H6 open after answer:', (await pg.inner_text('#help-open')).replace('\n',' | ') or '(пусто)')
        pas = await pg.evaluate("(() => { for (const [k, v] of window.__store) if (k.startsWith('products/') && k.endsWith('/meta/passport')) return v.text; })()")
        print('H6 passport tail:', pas[-260:].replace('\n',' | '))
        await pg.fill('#help-input', 'Какие роли есть?'); await pg.press('#help-input', 'Enter'); await answered(pg, 4)
        print('H7 partial:', (await pg.inner_text('#help-list .hq:last-child')).replace('\n',' | '))
        await pg.screenshot(path=os.path.join(D,'v13_help.png'), full_page=True)
        await pg.click('[data-mode=generate]'); await pg.wait_for_timeout(300)
        print('H8 back to generate: tabs visible', await pg.is_visible('#tabs'), '| run visible', await pg.is_visible('#btn-run'))
        await ctx.close()
        # standalone: history persists across reload
        ctx=await b.new_context(viewport={'width':390,'height':860})
        await ctx.add_init_script(path=os.path.join(D,'mockgen.js')); await ctx.add_init_script(path=os.path.join(D,'mock_ext.js'))
        await ctx.route('**/*', route)
        pg=await ctx.new_page(); pg.on('pageerror', lambda e: errs.append('S '+str(e)))
        await pg.goto('http://local.test/')
        await pg.evaluate("""() => { localStorage.clear(); localStorage.setItem('qapro.conns', JSON.stringify([{id:'aiX', kind:'openai', name:'LLM', baseUrl:'http://ai.test/v1', model:'m', apiKey:'k', auth:'Bearer', headers:'', tools:false}])); localStorage.setItem('tca.settings', JSON.stringify({genAI:'conn:aiX', mode:'help'})); }""")
        await pg.reload(); await pg.wait_for_timeout(1500)
        await pg.click('[data-act=help-view][data-v=qa]'); await pg.wait_for_timeout(200)
        await pg.fill('#help-input', 'Какой лимит запросов на сброс?'); await pg.click('#help-send'); await answered(pg, 1)
        print('S1 standalone answer (no passport, docs only):', (await pg.inner_text('#help-list .hq:last-child')).replace('\n',' | ')[:220])
        await pg.reload(); await pg.wait_for_timeout(1500)
        print('S2 after reload items:', await pg.evaluate("document.querySelectorAll('#help-list .hq').length"), '| W', await pg.evaluate('document.documentElement.scrollWidth'))
        await pg.screenshot(path=os.path.join(D,'v13_help_mobile.png'))
        await ctx.close()
        print('ERRORS', errs); await b.close()
asyncio.run(main())
