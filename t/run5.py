import asyncio, os
from playwright.async_api import async_playwright
D=os.path.dirname(os.path.abspath(__file__)); ROOT=os.path.dirname(D)
PROV="els=>els.map(e=>e.querySelector('b').textContent+':'+(e.classList.contains('on')?'выбран':'-')+':'+e.querySelector('.prov-st').textContent)"
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); errs=[]
        ctx=await b.new_context(viewport={'width':1360,'height':900})
        await ctx.add_init_script(path=os.path.join(D,'mockgen.js')); await ctx.add_init_script(path=os.path.join(D,'mock_ext.js'))
        pg=await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('file://'+os.path.join(ROOT,'qa-pro.html')); await pg.wait_for_timeout(800)
        print('RUN NOTE start:', await pg.inner_text('#run-note'))
        await pg.click('#btn-settings'); await pg.wait_for_timeout(150)
        print('P1 cards:', await pg.eval_on_selector_all('#prov-list .prov', PROV))
        print('P1 claude hint:', 'Anthropic не разрешает' in await pg.inner_text('#prov-list [data-prov=claude]'), '| fields:', await pg.is_visible('#pk-claude'), await pg.input_value('#pm-claude'))
        await pg.click('#prov-list [data-prov=openai] .prov-h'); await pg.wait_for_timeout(100)
        print('P2 openai model:', await pg.input_value('#pm-openai'), '| test disabled:', await pg.is_disabled('[data-prov-test=openai]'))
        print('P2 hint:', await pg.inner_text('#ai-hint'))
        await pg.fill('#pk-openai', 'sk-test'); await pg.wait_for_timeout(100)
        print('P3 status:', await pg.inner_text('#prov-st-openai'), '| focus kept:', await pg.evaluate("document.activeElement.id"), '| hint hidden:', await pg.is_hidden('#ai-hint'))
        await pg.click('[data-prov-test=openai]'); await pg.wait_for_timeout(400)
        print('P4 test:', await pg.inner_text('#prov-test-note'))
        ext = await pg.evaluate('window.__ext'); print('P4 call:', ext[-1]['u'], ext[-1]['auth'], ext[-1]['model'], 'temp' , ext[-1].get('temp'))
        await pg.click('#prov-list [data-prov=innocode] .prov-h'); await pg.fill('#pk-innocode', 'inno-key'); await pg.wait_for_timeout(50)
        print('P5 innocode url:', await pg.input_value('#pu-innocode'), '| model:', await pg.input_value('#pm-innocode'))
        print('P5 review options:', await pg.eval_on_selector_all('#review-ai option', 'os=>os.map(o=>o.textContent)'))
        await pg.select_option('#review-ai', 'conn:p-openai')
        await pg.click('#prov-list [data-prov=claude] .prov-h'); await pg.fill('#pk-claude', 'sk-ant-x'); await pg.wait_for_timeout(50)
        await pg.click('[data-prov-test=claude]'); await pg.wait_for_timeout(400)
        print('P6 claude test:', await pg.inner_text('#prov-test-note'), '| key header:', (await pg.evaluate('window.__ext'))[-1].get('key'))
        await pg.click('#prov-list [data-prov=innocode] .prov-h'); await pg.wait_for_timeout(50)
        print('P7 cards:', await pg.eval_on_selector_all('#prov-list .prov', PROV))
        await pg.screenshot(path=os.path.join(D,'v20_model_standalone.png'))
        await pg.click('#set-ov [data-close]')
        print('P7 run note:', await pg.inner_text('#run-note'))
        await pg.reload(); await pg.wait_for_timeout(800)
        st = await pg.evaluate("[JSON.parse(localStorage.getItem('tca.settings')).genAI, JSON.parse(localStorage.getItem('tca.settings')).reviewAI, JSON.parse(localStorage.getItem('qapro.conns')).map(c=>c.id+':'+(c.apiKey?'key':'-')+':'+c.model)]")
        print('P8 after reload:', st)
        await pg.click('#btn-run'); await pg.wait_for_selector('#btn-run:not([hidden])', timeout=30000); await pg.wait_for_timeout(500)
        calls = [e['u'] for e in await pg.evaluate('window.__ext')]
        print('P9 run calls inno.tech:', len([c for c in calls if 'inno.tech' in c]), '| temp:', [e.get('temp') for e in await pg.evaluate('window.__ext') if 'inno.tech' in e['u']][:1], '| tabs:', await pg.inner_text('#tabs'))
        await pg.click('#btn-review'); await pg.wait_for_selector('#btn-run:not([hidden])', timeout=30000); await pg.wait_for_timeout(500)
        calls = [e['u'] for e in await pg.evaluate('window.__ext')]
        print('P10 review via openai:', len([c for c in calls if 'openai' in c]))
        await ctx.close()
        # migration from innoGPT
        ctx=await b.new_context(viewport={'width':1360,'height':900})
        await ctx.add_init_script(path=os.path.join(D,'mock_ext.js'))
        await ctx.add_init_script(script="""if (!sessionStorage.getItem('seeded')) { sessionStorage.setItem('seeded','1'); localStorage.setItem('qapro.conns', JSON.stringify([{id:'p-innogpt',preset:'innogpt',kind:'openai',name:'Иннокод',baseUrl:'https://api.innogpt.de/v1',apiKey:'old',model:'gpt-4o',tools:true,noTemp:true}])); localStorage.setItem('tca.settings', JSON.stringify({genAI:'conn:p-innogpt', reviewAI:'conn:p-innogpt'})); }""")
        pg=await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('file://'+os.path.join(ROOT,'qa-pro.html')); await pg.wait_for_timeout(800)
        st = await pg.evaluate("[JSON.parse(localStorage.getItem('tca.settings')).genAI, JSON.parse(localStorage.getItem('tca.settings')).reviewAI, JSON.parse(localStorage.getItem('qapro.conns')).map(c=>c.id+':'+c.baseUrl+':'+c.model+':'+(c.apiKey?'key':'-'))]")
        print('MIG:', st, '| note:', await pg.inner_text('#run-note'))
        await ctx.close()
        # mobile settings
        ctx=await b.new_context(viewport={'width':390,'height':860}, color_scheme='dark')
        await ctx.add_init_script(path=os.path.join(D,'mock_ext.js'))
        pg=await ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('file://'+os.path.join(ROOT,'qa-pro.html')); await pg.wait_for_timeout(800)
        await pg.click('#btn-settings'); await pg.wait_for_timeout(150)
        print('M W', await pg.evaluate('document.documentElement.scrollWidth'))
        await pg.screenshot(path=os.path.join(D,'v20_model_mobile.png'))
        await pg.click('#settab-tms'); await pg.wait_for_timeout(100)
        await pg.screenshot(path=os.path.join(D,'v20_tms_mobile.png'))
        print('ERRORS', errs); await b.close()
asyncio.run(main())
